"""개인 연락처(PII) 마스킹 — 크롤링한 공고 본문에 섞인 이메일·전화번호를 저장 전에 지운다.

- 이메일            -> `[email]`
- 한국 전화번호     -> `[phone]`
    * 지역번호/휴대폰: 02-123-4567, 031-123-4567, 010-1234-5678, 0505-123-4567
    * 구분자 변형: 하이픈, 점, 공백 (`010 1234 5678`, `010.1234.5678`), `(02) 123-4567`
    * 국가번호: `+82 10-1234-5678`, `+82-2-123-4567`
    * 구분자 없는 번호: 01012345678(01X + 7~8자리), 0212345678(02 + 7~8자리), 0312345678(03x~06x + 7~8자리),
      07012345678. 반드시 `0` 으로 시작하고 앞뒤에 영숫자가 붙지 않아야 한다(금액·연도·`ID0212345678` 같은 식별자는 유지).

과마스킹 방지 원칙: 전화번호는 반드시 `0` 으로 시작하는 한국 지역/휴대폰 번호 형태여야 하고,
앞뒤에 다른 숫자가 붙어 있으면(날짜 2024-10-20, 급여 3000-4000, 긴 ID) 건드리지 않는다.
대표번호(1588-XXXX)는 개인 연락처가 아니므로 마스킹하지 않는다.
"""
from __future__ import annotations

import re
from typing import Optional

_EMAIL_RE = re.compile(r"[A-Za-z0-9._%+\-]+@[A-Za-z0-9\-]+(?:\.[A-Za-z0-9\-]+)+")

# 구분자: 하이픈/점(앞뒤 공백 허용) 또는 공백 하나. 개행은 구분자가 아니다(줄을 넘어 숫자를 합치지 않는다).
_SEP = r"(?:[ \t\u00a0]?[-.][ \t\u00a0]?|[ \t\u00a0])"
# 지역번호/휴대폰 접두: 0505(안심번호) | 02 | 031~09x(0으로 시작, 01x 포함, 00x 국제전화 제외)
_AREA = r"(?:050\d|02|0[13-9]\d)"

_PHONE_PATTERNS: list[re.Pattern[str]] = [
    # +82 10-1234-5678 / +82 (0)10 1234 5678 / +82-2-123-4567
    re.compile(
        r"(?<!\d)\+82" + r"[ \t\u00a0\-.]?" + r"\(?0?\)?" + r"(?:10|2|[3-6]\d|70)"
        + _SEP + r"?\d{3,4}" + _SEP + r"\d{4}(?!\d)"
    ),
    # (02) 123-4567
    re.compile(r"(?<!\d)\(" + _AREA + r"\)[ \t\u00a0]?\d{3,4}" + _SEP + r"\d{4}(?!\d)"),
    # 02-123-4567 / 010-1234-5678 (앞이 `숫자` 또는 `숫자+구분자` 이면 날짜·범위 숫자의 일부로 보고 제외)
    re.compile(r"(?<!\d)(?<!\d[-.])" + _AREA + _SEP + r"\d{3,4}" + _SEP + r"\d{4}(?!\d)"),
    # 구분자 없는 휴대폰 01012345678 (10~11자리)
    re.compile(r"(?<!\d)01[016-9]\d{7,8}(?!\d)"),
    # 구분자 없는 유선/인터넷전화: 0212345678, 0312345678, 07012345678 (앞에 영숫자 없음 → 식별자 제외)
    re.compile(r"(?<![A-Za-z0-9])(?:02\d{7,8}|0[3-6]\d\d{7,8}|070\d{7,8})(?!\d)"),
]


def mask_pii(text: Optional[str]) -> Optional[str]:
    """이메일은 `[email]`, 한국 전화번호는 `[phone]` 으로 치환. None/비문자열은 그대로 반환."""
    if not isinstance(text, str) or not text:
        return text
    out = _EMAIL_RE.sub("[email]", text)
    for pattern in _PHONE_PATTERNS:
        out = pattern.sub("[phone]", out)
    return out
